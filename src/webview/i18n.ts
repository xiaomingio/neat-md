let locale: Locale = 'en';

export function setLocale(value: Locale): void {
  locale = value;
  document.documentElement.lang = value;
}

export const t = (text: string): string => (locale === 'zh-CN' ? zh[text] ?? text : text);

/** Phrases for CodeMirror's built-in panels. */
export const phrases = (): Record<string, string> => (locale === 'zh-CN' ? zh : {});
